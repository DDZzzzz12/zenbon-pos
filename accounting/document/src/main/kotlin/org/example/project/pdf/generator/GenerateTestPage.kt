/**
 * Test page PDF generator.
 *
 * Creates a simple single-page PDF for printer testing via IPP.
 * Contains location name, printer URI, timestamp, and a confirmation message.
 *
 * @since 2.0.0
 * @author Generated with Claude Code
 */
package org.example.project.pdf.generator

import org.openpdf.text.Document
import org.openpdf.text.Element
import org.openpdf.text.Font
import org.openpdf.text.PageSize
import org.openpdf.text.Paragraph
import org.openpdf.text.pdf.BaseFont
import org.openpdf.text.pdf.PdfWriter
import org.openpdf.text.pdf.draw.LineSeparator
import java.awt.Color
import java.io.ByteArrayOutputStream

/**
 * Generates a test page PDF as a byte array.
 *
 * Creates a simple A4 PDF with printer location info, URI, and timestamp.
 * Used for testing IPP printers configured with PDF document format.
 *
 * @param locationName Printer location name (e.g., "Kitchen", "Bar")
 * @param printerUri IPP URI of the printer
 * @param timestamp Formatted timestamp string
 * @return PDF document bytes
 */
fun generateTestPagePdfBytes(
    locationName: String,
    printerUri: String,
    timestamp: String,
): ByteArray {
    val output = ByteArrayOutputStream()
    val document = Document(PageSize.A4, 50f, 50f, 50f, 50f)
    PdfWriter.getInstance(document, output)
    document.open()

    val baseFont = BaseFont.createFont(BaseFont.HELVETICA, BaseFont.CP1252, BaseFont.NOT_EMBEDDED)
    val baseFontBold = BaseFont.createFont(BaseFont.HELVETICA_BOLD, BaseFont.CP1252, BaseFont.NOT_EMBEDDED)
    val titleFont = Font(baseFontBold, 24f, Font.BOLD)
    val headerFont = Font(baseFontBold, 12f, Font.BOLD)
    val normalFont = Font(baseFont, 11f, Font.NORMAL)
    val successFont = Font(baseFontBold, 14f, Font.BOLD, Color(0, 128, 0))
    val smallFont = Font(baseFont, 9f, Font.NORMAL, Color.GRAY)

    // Title
    document.add(Paragraph(" ", normalFont))
    document.add(Paragraph(" ", normalFont))
    val title = Paragraph("TEST PRINT", titleFont)
    title.alignment = Element.ALIGN_CENTER
    title.spacingAfter = 30f
    document.add(title)

    // Separator
    document.add(LineSeparator(1f, 60f, Color.DARK_GRAY, Element.ALIGN_CENTER, -2f))
    document.add(Paragraph(" ", normalFont))

    // Details
    val locationLabel = Paragraph("Location:", headerFont)
    locationLabel.spacingBefore = 10f
    document.add(locationLabel)
    val locationValue = Paragraph(locationName, normalFont)
    locationValue.spacingAfter = 10f
    document.add(locationValue)

    val printerLabel = Paragraph("Printer URI:", headerFont)
    document.add(printerLabel)
    val printerValue = Paragraph(printerUri, normalFont)
    printerValue.spacingAfter = 10f
    document.add(printerValue)

    val dateLabel = Paragraph("Date:", headerFont)
    document.add(dateLabel)
    val dateValue = Paragraph(timestamp, normalFont)
    dateValue.spacingAfter = 20f
    document.add(dateValue)

    // Separator
    document.add(LineSeparator(1f, 60f, Color.DARK_GRAY, Element.ALIGN_CENTER, -2f))
    document.add(Paragraph(" ", normalFont))

    // Success message
    val successMsg = Paragraph("Print successful!", successFont)
    successMsg.alignment = Element.ALIGN_CENTER
    successMsg.spacingBefore = 20f
    document.add(successMsg)

    // Footer
    val footer = Paragraph("This is a test page generated by the POS system.", smallFont)
    footer.alignment = Element.ALIGN_CENTER
    footer.spacingBefore = 40f
    document.add(footer)

    document.close()
    return output.toByteArray()
}
