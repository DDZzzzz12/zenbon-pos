-- V67__add_promotions.sql
-- Adds promotion and bill_promotion tables for promotional voucher (Aktionsgutschein) support.
-- Promotions reduce the taxable base, unlike Mehrweg vouchers which are payment methods.

CREATE TABLE promotion (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(1000),
    discount_type VARCHAR(20) NOT NULL,
    discount_value DECIMAL(19, 4) NOT NULL,
    scope VARCHAR(20) NOT NULL,
    target_product_id BIGINT REFERENCES product(id),
    is_multi_use BOOLEAN NOT NULL DEFAULT FALSE,
    valid_from TIMESTAMP NOT NULL,
    valid_until TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by UUID NOT NULL REFERENCES employees(employee_id),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT chk_discount_type CHECK (discount_type IN ('FIXED_AMOUNT', 'PERCENTAGE', 'FREE_ITEM')),
    CONSTRAINT chk_scope CHECK (scope IN ('ITEM_SPECIFIC', 'BILL_WIDE')),
    CONSTRAINT chk_discount_value_positive CHECK (discount_value > 0),
    CONSTRAINT chk_item_specific_has_product CHECK (
        scope != 'ITEM_SPECIFIC' OR target_product_id IS NOT NULL
    )
);

CREATE TABLE bill_promotion (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    bill_id BIGINT NOT NULL REFERENCES bill(id) ON DELETE CASCADE,
    promotion_id BIGINT NOT NULL REFERENCES promotion(id),
    order_item_id BIGINT REFERENCES t_order_item(id),
    deducted_amount DECIMAL(19, 4) NOT NULL,
    applied_by UUID NOT NULL REFERENCES employees(employee_id),
    applied_at TIMESTAMP NOT NULL,
    CONSTRAINT chk_deducted_amount_positive CHECK (deducted_amount > 0)
);

ALTER TABLE bill ADD COLUMN promotion_amount DECIMAL(19, 4) NOT NULL DEFAULT 0;

CREATE INDEX idx_bill_promotion_bill_id ON bill_promotion(bill_id);
CREATE INDEX idx_bill_promotion_promotion_id ON bill_promotion(promotion_id);
CREATE INDEX idx_promotion_is_active ON promotion(is_active);
