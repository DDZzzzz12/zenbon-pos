#!/usr/bin/env python3
"""Placement of the mixed `shared` packages (ZenBon restructuring spec section 15, analysis A section 2).

The `shared` packages core.data.remote, core.data.remote.impl, core.utils (+ enumStrings, datev), core.network,
core.data.models and core.domain.models.setup hold files of every area side by side. The rule that places each file:

1. Placement = the HIGHEST area among the file's imports, computed as a fixpoint over the set: an import of another file
   of the set uses that file's COMPUTED placement; a same-package reference without import counts as an import (the
   top-level name is found by the word-boundary scan of same_package_refs; a name declared by two files of the package
   is ambiguous and ignored). No upward import = platform.
2. `Ktor<X>ApiClient` (impl) = max(its own placement, its interface `<X>ApiClient`'s placement).
3. core/utils/enumStrings/*: matched by RECEIVER type (`fun <Enum>.getName(language)`); the area is the enum's.
4. Conflict: a NON-ui file placed in a lower area that imports a set file is not a placement; it is reported
   (SPLIT / RE-HOME / PORT item). ui importers (ui/*) and the host are exempt (spec 5.3).
5. Hand placements (placement-overrides.tsv rows outside the generated block) are fixed: dependents follow them, and a
   differing computed area is reported, never emitted.

Output: the generated block `# BEGIN shared-placement` .. `# END shared-placement` in config/structure/placement-overrides.tsv
(rows only for files NOT placed in platform, which is the default for `shared`) and docs/audit/2026-10-26-shared-placement.md.

Usage: python3 -I scripts/structure/shared_placement.py
"""
from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Callable, NamedTuple

sys.path.insert(0, str(Path(__file__).resolve().parent))
import move_manifest as mm  # noqa: E402
import same_package_refs as spr  # noqa: E402
import upward_refs as ur  # noqa: E402

ROOT = ur.ROOT
PROJECT = "org.example.project."
SET_PACKAGES = frozenset({"core.data.remote", "core.data.remote.impl", "core.utils", "core.utils.enumStrings", "core.utils.datev",
                          "core.network", "core.data.models", "core.domain.models.setup"})
ENUM_STRINGS = "core.utils.enumStrings"
BEGIN = "# BEGIN shared-placement (generated by scripts/structure/shared_placement.py; do not edit)"
END = "# END shared-placement"
RANK = {area: i for i, area in enumerate(ur.AREAS)}
ANALYSIS_REMOTE = ROOT / "docs/audit/2026-10-26-platform-extraction-remote-clients.tsv"
ANALYSIS_PLACEMENT = ROOT / "docs/audit/2026-10-26-platform-extraction-shared-placement.tsv"
# Files that mix areas and are SPLIT by a later task: never placed here (no row). Dependents are computed as if the file sat in the
# area of the part its non-ui users need, so the unsplit file does not drag them up. path -> (assumed area, why)
# (empty since Task 14 split core/utils/PaymentNameExt.kt)
SPLIT_PENDING: dict[str, tuple[str, str]] = {}
_RECEIVER = re.compile(r"^(?:@[\w.]+(?:\([^)]*\))?\s+)*(?:(?:public|internal|inline|suspend|operator|infix)\s+)*fun\s+(?:<[^>]*>\s*)?([A-Z][\w]*)(?:<[^>]*>)?\??\.\w+\s*\(", re.MULTILINE)
_KTOR = re.compile(r"^Ktor(\w+ApiClient)\.kt$")


class Solution(NamedTuple):
    placed: dict[str, str]                       # path -> area (fixed rows applied)
    reasons: dict[str, str]                      # path -> the highest import that decided it ("-" for platform)
    free: dict[str, str]                         # path -> area computed WITHOUT the fixed rows
    disagreements: dict[str, tuple[str, str]]    # path -> (fixed area, computed area) where they differ
    ambiguous: list[tuple[str, str]]             # (user path, ambiguous name) same-package names ignored


class Importer(NamedTuple):
    path: str
    area: str                                    # platform..backoffice, `ui`, or `host/wiring`
    imports: list[str]


class Conflict(NamedTuple):
    importer: str
    importer_area: str
    target: str                                  # set file path (relative)
    placed: str
    symbol: str


def _package(text: str) -> str:
    package = spr.package_of(text) or ""
    return package[len(PROJECT.rstrip(".")) + 1:] if package.startswith(PROJECT) else package


def _name_index(files: dict[str, str]) -> dict[tuple[str, str], list[str]]:
    index: dict[tuple[str, str], list[str]] = defaultdict(list)
    for path, text in sorted(files.items()):
        package = _package(text)
        for name in spr.declared_names(text):
            index[(package, name)].append(path)
    return index


def resolve_set_import(fqn: str, files: dict[str, str], index: dict[tuple[str, str], list[str]]) -> tuple[str | None, bool]:
    """(set file path, ambiguous) for an import of a set-file symbol. `(None, False)` = not a set symbol."""
    if not fqn.startswith(PROJECT):
        return None, False
    segments = fqn[len(PROJECT):].split(".")
    cut = next((i for i, s in enumerate(segments) if s[:1].isupper()), len(segments) - 1)
    package, name = ".".join(segments[:cut]), segments[cut]
    found = index.get((package, name))
    if found:
        return (found[0], False) if len(found) == 1 else (None, True)
    path = ur.import_file(fqn)
    return (path, False) if path in files else (None, False)


def _package_index(files: dict[str, str]) -> dict[str, list[str]]:
    index: dict[str, list[str]] = defaultdict(list)
    for path, text in sorted(files.items()):
        index[_package(text)].append(path)
    return index


def _receivers(text: str) -> list[str]:
    return sorted(set(_RECEIVER.findall(spr.code_only(text))))


def _enum_fqn(simple: str, imports: list[str]) -> str | None:
    return next((fqn for fqn in imports if fqn.rsplit(".", 1)[-1] == simple), None)


Edge = tuple[str, str, str]  # (kind, label, target) kind: area | set


def _edges(path: str, files: dict[str, str], imports: dict[str, list[str]], area_of_import: Callable[[str], str | None],
           index: dict[tuple[str, str], list[str]], ambiguous: list[tuple[str, str]], packages: dict[str, list[str]]) -> list[Edge]:
    text = files[path]
    package = _package(text)
    own = imports.get(path, [])
    edges: list[Edge] = []
    if package == ENUM_STRINGS:
        for receiver in _receivers(text):
            fqn = _enum_fqn(receiver, own)
            area = area_of_import(fqn) if fqn else None
            if area in RANK:
                edges.append(("area", fqn or receiver, area))
        return edges
    for fqn in own:
        if fqn.endswith("."):  # `import a.b.*`: an edge to every file of the package at its computed placement
            wildcard = packages.get(fqn.removeprefix(PROJECT).rstrip("."), [])
            if wildcard:
                edges += [("set", f"{fqn.removeprefix(PROJECT)}*", other) for other in wildcard if other != path]
                continue
        target, is_ambiguous = resolve_set_import(fqn, files, index)
        if is_ambiguous:
            ambiguous.append((path, fqn.rsplit(".", 1)[-1]))
        elif target is not None:
            if target != path:
                edges.append(("set", fqn.removeprefix(PROJECT), target))
            continue
        else:
            area = area_of_import(fqn)
            if area in RANK:
                edges.append(("area", fqn.removeprefix(PROJECT), area))
    body = re.sub(re.escape(PROJECT + package) + r"\.\w+", "", spr._IMPORT_LINE.sub("", spr.code_only(text)))
    tokens = set(re.findall(r"\w+", body))
    for name in sorted(tokens):
        owners = index.get((package, name), [])
        if len(owners) > 1:
            if path not in owners:
                ambiguous.append((path, name))
        elif len(owners) == 1 and owners[0] != path:
            edges.append(("set", f"same-package {name}", owners[0]))
    match = _KTOR.match(path.rsplit("/", 1)[-1])
    if match:
        interface = f"{path.rsplit('/impl/', 1)[0]}/{match.group(1)}.kt" if "/impl/" in path else None
        if interface in files:
            edges.append(("set", f"interface {match.group(1)}", interface))
    return edges


def _fixpoint(edges: dict[str, list[Edge]], fixed: dict[str, str]) -> tuple[dict[str, str], dict[str, str]]:
    placed = {path: fixed.get(path, "platform") for path in edges}
    reasons = {path: "-" for path in edges}
    changed = True
    while changed:
        changed = False
        for path in sorted(edges):
            if path in fixed:
                continue
            best, why = placed[path], reasons[path]
            for kind, label, target in sorted(edges[path]):
                area = target if kind == "area" else placed[target]
                if RANK[area] > RANK[best]:
                    best, why = area, label
            if best != placed[path]:
                placed[path], reasons[path], changed = best, why, True
    return placed, reasons


def solve(files: dict[str, str], imports: dict[str, list[str]], area_of_import: Callable[[str], str | None],
          fixed: dict[str, str] | None = None) -> Solution:
    fixed = {p: a for p, a in (fixed or {}).items() if p in files}
    index = _name_index(files)
    ambiguous: list[tuple[str, str]] = []
    packages = _package_index(files)
    edges = {path: _edges(path, files, imports, area_of_import, index, ambiguous, packages) for path in files}
    placed, reasons = _fixpoint(edges, fixed)
    free, _ = _fixpoint(edges, {})
    disagreements = {p: (a, free[p]) for p, a in sorted(fixed.items()) if free[p] != a}
    return Solution(placed, reasons, free, disagreements, sorted(set(ambiguous)))


def place(files: dict[str, str], imports: dict[str, list[str]], area_of_import: Callable[[str], str | None],
          fixed: dict[str, str] | None = None) -> dict[str, str]:
    return solve(files, imports, area_of_import, fixed).placed


def find_conflicts(files: dict[str, str], placed: dict[str, str], importers: list[Importer]) -> list[Conflict]:
    index = _name_index(files)
    conflicts: list[Conflict] = []
    for importer in importers:
        if importer.area not in RANK:  # ui/* and host/wiring see every area
            continue
        for fqn in importer.imports:
            target, _ = resolve_set_import(fqn, files, index)
            if target is not None and RANK[placed[target]] > RANK[importer.area]:
                conflicts.append(Conflict(importer.path, importer.area, target, placed[target], fqn.rsplit(".", 1)[-1]))
    return sorted(set(conflicts))


# --- generated block -----------------------------------------------------------------------------------------------

def split_block(text: str) -> tuple[str, str]:
    """(text without the generated block, the block). Both markers must be present to count as a block."""
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        return text, ""
    after = end + len(END)
    after += 1 if text[after:after + 1] == "\n" else 0
    return text[:start] + text[after:], text[start:after]


def render_block(rows: list[tuple[str, str, str]]) -> str:
    return "".join([BEGIN + "\n", *(f"{path}\t{area}:api\t{reason}\n" for path, area, reason in sorted(rows)), END + "\n"])


def replace_block(text: str, rows: list[tuple[str, str, str]]) -> str:
    manual, _ = split_block(text)
    manual = manual if manual.endswith("\n") or not manual else manual + "\n"
    return manual + render_block(rows)


# --- real tree -----------------------------------------------------------------------------------------------------

def set_files(tree: dict[str, str]) -> tuple[dict[str, str], dict[str, list[str]]]:
    """rel path -> text and rel path -> imports of the non-test `shared` files in the mixed packages (source sets merged).

    Files already extracted from `shared` (the in-place modules of module-dirs.tsv whose source module is `shared`) count as `shared`."""
    modules = {"shared", *mm.in_place_of("shared")}
    texts: dict[str, list[str]] = defaultdict(list)
    for path, text in sorted(tree.items()):
        located = mm.package_of(path, text)
        if located is None or located[0] not in modules or mm.is_test(located[1]) or located[2] not in SET_PACKAGES:
            continue
        texts[ur.rel_path(path)].append(text)
    files = {rel: "\n".join(parts) for rel, parts in texts.items()}
    imports = {rel: sorted(set(ur._IMPORT.findall(text))) for rel, text in files.items()}
    return files, imports


def importer_areas(scanned: dict[str, str], tree: dict[str, str], set_rels: set[str]) -> list[Importer]:
    """Every production file outside the set with the area it will live in (`ui` for ui/*, `host/wiring` for the host)."""
    targets, _ = spr.effective_targets(tree)
    own_roots = ("shared/", *(f"{d}/" for d, row in mm.in_place_dirs().items() if row.source_module == "shared"))
    importers: list[Importer] = []
    for path, text in sorted(scanned.items()):
        if ur.rel_path(path) in set_rels and path.startswith(own_roots):
            continue
        head = path.split("/", 1)[0]
        if head == "ui":
            area = "ui"
        elif head in ur.AREAS:
            area = head
        elif path in targets:
            area = spr.area_of(targets[path])
            area = "host/wiring" if area == "host" else area
        else:
            area = "host/wiring"
        found = ur._IMPORT.findall(text)
        if found:
            importers.append(Importer(path, area, found))
    return importers


def feature_area(rel: str, areas: dict[str, str], overrides: dict[str, str]) -> str:
    """The file-name heuristic the analysis calls a cross-check: the area of the feature the file name begins with."""
    name = mm.feature_of_filename(rel, areas)
    return (ur.package_area_for(name, areas, overrides) if name else None) or "platform"


def read_analysis() -> dict[str, str]:
    """file name -> area the analysis (A section 2 / its own fixpoint result) gave it."""
    result: dict[str, str] = {}
    if ANALYSIS_REMOTE.exists():
        for line in ANALYSIS_REMOTE.read_text(encoding="utf-8").splitlines():
            parts = line.split("\t")
            if len(parts) >= 3:
                result[parts[2]] = parts[0]
    if ANALYSIS_PLACEMENT.exists():
        for line in ANALYSIS_PLACEMENT.read_text(encoding="utf-8").splitlines():
            parts = line.split("\t")
            if len(parts) >= 3 and parts[1] not in result:
                result[parts[1]] = parts[2].removeprefix("place=")
    return result


def render_report(files: dict[str, str], solution: Solution, rows: list[tuple[str, str, str]], conflicts: list[Conflict],
                  manual: dict[str, str], feature: dict[str, str], analysis: dict[str, str]) -> str:
    placed = solution.placed
    counts: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for path, area in placed.items():
        directory = path.rsplit("/", 1)[0]
        counts[directory][area] += 1
    out = ["# Placement of the mixed shared packages", "",
           "Generated by `scripts/structure/shared_placement.py`; do not edit by hand. Rule: analysis A section 2 (highest import, fixpoint over the set, "
           "`Ktor<X>ApiClient` = max(own, interface), enumStrings by receiver type, lower-area non-ui importer = conflict). "
           f"{len(files)} files, {len(manual)} hand-placed, {len(rows)} generated rows (files outside platform with no manual row).", "",
           "## Counts per directory and area", "", "| directory | " + " | ".join(ur.AREAS) + " | total |", "|---|" + "---|" * (len(ur.AREAS) + 1)]
    for directory in sorted(counts):
        row = counts[directory]
        out.append(f"| `{directory}` | " + " | ".join(str(row.get(a, 0)) for a in ur.AREAS) + f" | {sum(row.values())} |")
    remote = {p: a for p, a in placed.items() if p.startswith("core/data/remote")}
    ana_remote = defaultdict(int)
    for path in remote:
        ana_remote[analysis.get(path.rsplit("/", 1)[-1], "?")] += 1
    ours = defaultdict(int)
    for area in remote.values():
        ours[area] += 1
    out += ["", "## remote + impl against the analysis (platform 28, ecr 40, fiscal 15, accounting 26, backoffice 6)", "",
            "| area | this tool | analysis (per file) |", "|---|---|---|"]
    out += [f"| {a} | {ours.get(a, 0)} | {ana_remote.get(a, 0)} |" for a in ur.AREAS]
    diffs = [(p, analysis[p.rsplit('/', 1)[-1]], placed[p]) for p in sorted(placed) if p.rsplit("/", 1)[-1] in analysis and analysis[p.rsplit('/', 1)[-1]] != placed[p]]
    out += ["", f"## Differences from the analysis ({len(diffs)})", "", "| file | analysis | this tool | decided by |", "|---|---|---|---|"]
    out += [f"| `{p}` | {a} | {b} | {'hand placement' if p in manual else 'SPLIT pending, unplaced' if p in SPLIT_PENDING else solution.reasons[p]} |" for p, a, b in diffs] or ["| none | | | |"]
    out += ["", f"## Conflicts: non-ui importers in a lower area ({len(conflicts)})", "",
            "Each is a SPLIT / RE-HOME / PORT item; this tool does not fix them.", "", "| importer | its area | imports | placed in | file |", "|---|---|---|---|---|"]
    out += [f"| `{c.importer}` | {c.importer_area} | `{c.symbol}` | {c.placed} | `{c.target}` |" for c in conflicts] or ["| none | | | | |"]
    out += ["", f"## Hand placements that differ from the fixpoint ({sum(1 for p in solution.disagreements if p not in SPLIT_PENDING)})", "", "| file | hand | computed |", "|---|---|---|"]
    out += [f"| `{p}` | {m} | {c} |" for p, (m, c) in solution.disagreements.items() if p not in SPLIT_PENDING] or ["| none | | |"]
    cross = [(p, feature[p], placed[p]) for p in sorted(placed) if feature[p] != placed[p] and p not in manual]
    out += ["", f"## File-name feature heuristic against the fixpoint ({len(cross)} differ; the fixpoint decides)", "", "| file | by name | fixpoint |", "|---|---|---|"]
    out += [f"| `{p}` | {a} | {b} |" for p, a, b in cross] or ["| none | | |"]
    out += ["", f"## SPLIT items left unplaced ({len(SPLIT_PENDING)})", ""]
    out += [f"- `{p}`: {why}" for p, (_, why) in SPLIT_PENDING.items()]
    out += ["", f"## Same-package names ignored as ambiguous ({len(solution.ambiguous)})", "",
            "A top-level name declared by two files of one package (for example `getName` in enumStrings) cannot be attributed; those uses add no edge.", ""]
    out += [f"- `{p}`: `{n}`" for p, n in solution.ambiguous]
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    areas = ur.load_table((ROOT / "config/structure/package-areas.tsv").read_text(encoding="utf-8"))
    overrides = ur.load_overrides((ROOT / "config/structure/package-overrides.tsv").read_text(encoding="utf-8"))
    tsv = ROOT / "config/structure/placement-overrides.tsv"
    text = tsv.read_text(encoding="utf-8")
    manual_text, _ = split_block(text)
    manual_placements = ur.load_placement_overrides(manual_text)
    generated = ur.load_file_overrides_file()
    tree = mm.collect_files()
    scanned = ur.collect_files()
    files, imports = set_files(tree)
    manual = {p: pl.area for p, pl in manual_placements.items() if p in files}
    try:
        merged = ur.merge_placements(manual_placements, generated)
    except ValueError as error:
        sys.stderr.write(f"{error}\n")
        return 1
    rels = {ur.rel_path(p) for p in scanned}

    def area_of_import(fqn: str) -> str | None:
        return ur.import_area(fqn, areas, overrides, merged, rels)

    split = {p: area for p, (area, _) in SPLIT_PENDING.items() if p in files}
    solution = solve(files, imports, area_of_import, {**split, **manual})
    rows = [(p, a, f"fixpoint: {solution.reasons[p]}") for p, a in sorted(solution.placed.items()) if a != "platform" and p not in manual and p not in split]
    conflicts = find_conflicts(files, solution.placed, importer_areas(scanned, tree, set(files)))
    feature = {p: feature_area(p, areas, overrides) for p in files}
    tsv.write_text(replace_block(text, rows), encoding="utf-8")
    (ROOT / "docs/audit/2026-10-26-shared-placement.md").write_text(
        render_report(files, solution, rows, conflicts, manual, feature, read_analysis()), encoding="utf-8")
    sys.stdout.write(f"shared_placement: {len(files)} files, {len(rows)} generated rows, {len(conflicts)} conflicts, {len(solution.disagreements)} hand/fixpoint disagreements\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
