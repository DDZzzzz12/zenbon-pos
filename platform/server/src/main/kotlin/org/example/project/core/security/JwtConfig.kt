/**
 * JWT configuration and token management.
 *
 * Handles JWT token creation, validation, and extraction of user claims
 * with support for employee permissionEnums and development mode.
 */
@OptIn(ExperimentalTime::class)
object JwtConfig {
    private val logger = LoggerFactory.getLogger(JwtConfig::class.java)
    private val config = YamlConfigLoader.load()

    // JWT Configuration from application.yaml
    private val JWT_SECRET = config.getString("security.jwt.secret")
    private val JWT_ISSUER = config.getString("security.jwt.issuer")
    private val JWT_AUDIENCE = config.getString("security.jwt.audience")
    private val JWT_REALM = config.getString("security.jwt.realm")

    // Token expiration times from configuration
    private val REFRESH_TOKEN_EXPIRY_DAYS = config.getInt("security.jwt.refreshTokenExpiryDays")
    private val ACCESS_TOKEN_EXPIRY_MINUTES = config.getInt("security.jwt.accessTokenExpiryMinutes")

    // Development mode flag from configuration
    var isDevelopmentMode: Boolean = config.getBoolean("security.jwt.developmentMode")
        private set

    /** True while the server runs in JWT development mode — dev tooling (API docs) is on by default then. */
    val devToolingEnabled: Boolean
        get() = isDevelopmentMode

    private val algorithm = Algorithm.HMAC256(JWT_SECRET)

    /** `tokenType` of the config-defined maintainer's JWT. [validateToken] refuses it. */
    const val MAINTAINER_TOKEN_TYPE = "maintainer"
    const val MAINTAINER_SUBJECT = "maintainer"

    val verifier =
        JWT
            .require(algorithm)
            .withIssuer(JWT_ISSUER)
            .withAudience(JWT_AUDIENCE)
            .build()

    /**
     * Builds a signed access token shared by [generateAccessToken] and [generateStationAccessToken]
     * so their claim set, expiry computation and signing chain cannot drift apart.
     *
     * [extraClaims] are added after the standard `tokenType` claim and before the timestamps, so
     * callers get to append token-specific claims (e.g. `station`) without touching the shared
     * shape. [logJti] lets each caller keep its own log wording while still logging the jti that
     * actually ended up in the signed token.
     */
    private fun buildAccessToken(
        employeeId: String,
        employeeNumber: String,
        role: String,
        deviceId: String,
        extraClaims: Map<String, String> = emptyMap(),
        logJti: (String) -> Unit,
    ): String {
        val now = Clock.System.now()
        val timeZone = getTimeZone()
        val expiry = now.plus(DateTimePeriod(minutes = ACCESS_TOKEN_EXPIRY_MINUTES), timeZone)

        // Generate unique token ID for blacklist support
        val jti = UUID.randomUUID().toString()
        logJti(jti)

        var builder =
            JWT
                .create()
                .withJWTId(jti) // Unique token ID for blacklist
                .withIssuer(JWT_ISSUER)
                .withAudience(JWT_AUDIENCE)
                .withSubject(employeeId)
                .withClaim("employeeNumber", employeeNumber)
                .withClaim("role", role)
                .withClaim("deviceId", deviceId)
                .withClaim("tokenType", "access")

        extraClaims.forEach { (key, value) -> builder = builder.withClaim(key, value) }

        return builder
            .withIssuedAt(Date.from(now.toJavaInstant()))
            .withExpiresAt(Date.from(expiry.toJavaInstant()))
            .sign(algorithm)
    }

    /**
     * Generates an access token for an authenticated employee.
     *
     * Uses the client's device ID from X-Device-ID header directly. This device ID
     * is generated by DeviceInfoProvider on the client and remains consistent
     * across sessions for the same physical device.
     *
     * @param employeeId Employee's unique identifier
     * @param employeeNumber Employee's number
     * @param permissionEnums Set of employee permissionEnums
     * @param deviceId Device identifier from X-Device-ID header (consistent per device)
     * @return JWT access token string containing the deviceId
     */
    fun generateAccessToken(
        employeeId: String,
        employeeNumber: String,
        role: String,
        deviceId: String? = null,
    ): String {
        // Use client-provided device ID directly (from DeviceInfoProvider via X-Device-ID header)
        // Falls back to "unknown" if header not provided
        val finalDeviceId = deviceId ?: "unknown"

        return buildAccessToken(employeeId, employeeNumber, role, finalDeviceId) { jti ->
            logger.debug("Generating access token for employee with deviceId: $finalDeviceId, jti: $jti")
        }
    }

    /**
     * Generates the access token a login-less station runs the till shell with.
     *
     * Same shape and lifetime as [generateAccessToken], plus a `station` claim carrying the
     * terminal's role name. The subject is the shared `terminal-device` employee and the role is
     * always TERMINAL_DEVICE — a station never runs as a person. [deviceId] must be the terminal's
     * PHYSICAL device id (the `device_id` column), which is what `findByDeviceId` matches.
     */
    fun generateStationAccessToken(
        employeeId: String,
        employeeNumber: String,
        deviceId: String,
        station: String,
    ): String =
        buildAccessToken(
            employeeId = employeeId,
            employeeNumber = employeeNumber,
            role = EmployeeRole.TERMINAL_DEVICE.name,
            deviceId = deviceId,
            extraClaims = mapOf("station" to station),
        ) { jti ->
            logger.debug("Generating station access token for deviceId: $deviceId, station: $station, jti: $jti")
        }

    /**
     * Mints the maintainer's access token.
     *
     * Same secret, issuer and audience as every other token, but a different SHAPE: subject
     * `maintainer`, `tokenType=maintainer`, and none of `employeeNumber`/`role`/`deviceId`. That is
     * the containment: [validateToken] answers null for it, so nothing that decodes an employee or
     * device identity can mistake it for one, and the `auth-jwt` provider (which requires an
     * `employeeNumber`) rejects it too. No refresh token: the maintainer logs in again.
     */
    fun generateMaintainerToken(lifetimeMinutes: Int): String {
        val now = java.time.Instant.now()
        return JWT
            .create()
            .withJWTId(UUID.randomUUID().toString())
            .withIssuer(JWT_ISSUER)
            .withAudience(JWT_AUDIENCE)
            .withSubject(MAINTAINER_SUBJECT)
            .withClaim("tokenType", MAINTAINER_TOKEN_TYPE)
            .withIssuedAt(Date.from(now))
            .withExpiresAt(Date.from(now.plusSeconds(lifetimeMinutes * 60L)))
            .sign(algorithm)
    }

    /**
     * Verifies a maintainer token. Null for anything else: an expired, forged or foreign-signed
     * token, an employee/refresh/station token, or a subject that is not the maintainer.
     */
    fun validateMaintainerToken(token: String): MaintainerClaims? =
        try {
            val decoded = verifier.verify(token)
            if (decoded.getClaim("tokenType").asString() == MAINTAINER_TOKEN_TYPE && decoded.subject == MAINTAINER_SUBJECT) {
                MaintainerClaims(
                    jti = decoded.id,
                    issuedAt = decoded.issuedAt?.toInstant(),
                    expiresAt = decoded.expiresAt?.toInstant(),
                )
            } else {
                null
            }
        } catch (e: JWTVerificationException) {
            logger.debug("Maintainer token validation failed: ${e.message}")
            null
        }

    /**
     * Generates a refresh token for token renewal.
     *
     * Preserves the deviceId from the original access token to maintain device
     * binding throughout the token refresh lifecycle.
     *
     * @param employeeId Employee's unique identifier
     * @param deviceId Device identifier from original access token
     * @return JWT refresh token string
     */
    fun generateRefreshToken(
        employeeId: String,
        deviceId: String,
    ): String {
        val now = Clock.System.now()
        val timeZone = getTimeZone()
        val expiry = now.plus(DateTimePeriod(days = REFRESH_TOKEN_EXPIRY_DAYS), timeZone)

        // Generate unique token ID for blacklist support
        val jti = UUID.randomUUID().toString()

        logger.debug("Generating refresh token for employee with deviceId: $deviceId, jti: $jti")

        return JWT
            .create()
            .withJWTId(jti) // Unique token ID for blacklist
            .withIssuer(JWT_ISSUER)
            .withAudience(JWT_AUDIENCE)
            .withSubject(employeeId)
            .withClaim("deviceId", deviceId)
            .withClaim("tokenType", "refresh")
            .withIssuedAt(Date.from(now.toJavaInstant()))
            .withExpiresAt(Date.from(expiry.toJavaInstant()))
            .sign(algorithm)
    }

    /**
     * Validates and decodes a JWT token.
     *
     * Extracts all claims including the server-generated deviceId for secure
     * device identification without relying on client-controlled headers.
     *
     * @param token JWT token string
     * @return TokenClaims if valid, null if invalid
     */
    fun validateToken(token: String): TokenClaims? =
        try {
            val decodedJWT = verifier.verify(token)

            // A maintainer token is signed with the same key but is neither an employee nor a device.
            // Answering null here closes every caller of validateToken to it in one place.
            if (decodedJWT.getClaim("tokenType").asString() == MAINTAINER_TOKEN_TYPE) {
                null
            } else {
                // Extract deviceId from token (server-generated, cryptographically signed)
                val deviceId = decodedJWT.getClaim("deviceId").asString() ?: "unknown"

                // Extract JTI for blacklist support
                val jti = decodedJWT.id // JWT ID claim

                TokenClaims(
                    employeeId = decodedJWT.subject,
                    employeeNumber = decodedJWT.getClaim("employeeNumber").asString() ?: "",
                    role = decodedJWT.getClaim("role").asString() ?: "",
                    deviceId = deviceId,
                    tokenType = decodedJWT.getClaim("tokenType").asString() ?: "access",
                    jti = jti,
                    issuedAt = decodedJWT.issuedAt?.toInstant()?.let { Instant.fromEpochMilliseconds(it.toEpochMilli()) },
                    expiresAt = decodedJWT.expiresAt?.toInstant()?.let { Instant.fromEpochMilliseconds(it.toEpochMilli()) },
                    // Absent on every login/refresh token: asString() answers null for a missing claim.
                    station = decodedJWT.getClaim("station").asString(),
                )
            }
        } catch (e: JWTVerificationException) {
            logger.debug("Token validation failed: ${e.message}")
            null
        }

    /**
     * Checks if a token is expired.
     *
     * @param token JWT token string
     * @return true if expired, false if valid
     */
    fun isTokenExpired(token: String): Boolean =
        // Only a token that is OUR token and has run out counts as expired. The verifier checks the
        // signature before the time claims, so TokenExpiredException implies a genuine token. The
        // old version answered true for anything that failed to verify — a garbage or tampered
        // bearer came back as AUTH_SESSION_EXPIRED ("please refresh") instead of
        // AUTH_INVALID_CREDENTIALS.
        try {
            verifier.verify(token)
            false
        } catch (e: TokenExpiredException) {
            true
        } catch (e: JWTVerificationException) {
            false
        }

    /**
     * Extracts the bearer token from Authorization header.
     *
     * The scheme is matched case-insensitively (RFC 7235), as Ktor's own header parser does: a guard
     * that only knew `Bearer ` would be skipped by `bearer <token>` while the auth provider still
     * read the token. This is the one parser every such guard uses.
     *
     * @param authorizationHeader The Authorization header value
     * @return The trimmed token without the scheme, or null if the header is absent, not a bearer
     *   header, or carries an empty token
     */
    fun extractBearerToken(authorizationHeader: String?): String? =
        authorizationHeader
            ?.takeIf { it.regionMatches(0, "Bearer ", 0, 7, ignoreCase = true) }
            ?.substring(7)
            ?.trim()
            ?.takeIf { it.isNotEmpty() }

    /**
     * Gets JWT configuration values for Ktor setup.
     */
    fun getJwtRealm(): String = JWT_REALM

    fun getJwtIssuer(): String = JWT_ISSUER

    fun getJwtAudience(): String = JWT_AUDIENCE

    fun getAlgorithm(): Algorithm = algorithm

    fun getExpirationTime(): Long = ACCESS_TOKEN_EXPIRY_MINUTES.toLong() * 60

    fun getRawSecret(): String = JWT_SECRET

    /**
     * Sets development mode flag.
     * Should only be used during application initialization.
     *
     * @param enabled Whether development mode is enabled
     */
    fun setDevelopmentMode(enabled: Boolean) {
        isDevelopmentMode = enabled
        logger.info("JWT development mode: $enabled")
    }
}

