/**
 * A capability as it arrives on the wire (`CapabilityInfoDto.name`, e.g. `CATALOG_READ`) as the
 * operator reads it — „Artikelstamm ansehen“. Keyed by the wire name, not the client enum, because
 * the catalog comes from the SERVER: a capability this client has no label for (a newer server's) is
 * shown as its code rather than dropped or rendered as a key id (QA admin19 NOTE-c).
 */
fun localizedCapabilityName(
    name: String,
    language: Language,
): String = CAPABILITY_KEYS[name]?.let { getString(it, language) } ?: name

/**
 * A capability area — the first segment of a capability name (`CATALOG`) — as the operator reads it,
 * falling back to the segment itself.
 */
fun localizedCapabilityArea(
    area: String,
    language: Language,
): String = AREA_KEYS[area]?.let { getString(it, language) } ?: area

